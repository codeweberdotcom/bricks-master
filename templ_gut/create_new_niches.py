def make_json(niche):
    meta = niche["meta"]
    site = niche["site"]
    adv0_title = niche["adv0"]
    name = site["name"]

    # Deep-copy common template and fill in placeholders
    import copy
    common = copy.deepcopy(COMMON_TEMPLATE)
    common["advantages"]["items"][0]["title"] = adv0_title
    common["about"]["lead"] = common["about"]["lead"].replace("PLACEHOLDER", name)
    common["video"]["badge"] = common["video"]["badge"].replace("PLACEHOLDER", name)
    common["video"]["variants"][3]["title"] = common["video"]["variants"][3]["title"].replace("PLACEHOLDER", name)

    return {
        "meta": {
            "schema": "codeweber-site",
            "version": 1,
            "key": meta["key"],
            "group": meta["group"],
            "generated": "2026-06-11",
        },
        "site": site,
        "common": common,
    }


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for niche in NICHES:
        num = niche["meta"]["num"]
        key = niche["meta"]["key"]
        filename = f'{num:02d}-{key}.json'
        filepath = os.path.join(OUT_DIR, filename)
        data = make_json(niche)
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f'  created: {filename}')
    print(f'\nDone: {len(NICHES)} files created in {OUT_DIR}')


if __name__ == '__main__':
    main()
